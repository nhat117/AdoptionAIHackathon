"""Report six real two-hop handoffs as integration evidence, not attack ASR."""

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "runs/agent-handoff-smoke-v1"
OUTPUT = ROOT.parents[1] / "outputs/multi-agent-oversight"


def main():
    spec = json.loads((FOLDER / "FROZEN_PROTOCOL.json").read_text())["spec"]
    for name, expected in spec["source_sha256"].items():
        assert hashlib.sha256((ROOT / name).read_bytes()).hexdigest() == expected
    assert (
        hashlib.sha256((FOLDER / "inputs.jsonl").read_bytes()).hexdigest()
        == spec["inputs_sha256"]
    )
    rows = [json.loads(x) for x in (FOLDER / "trials.jsonl").read_text().splitlines()]
    assert len(rows) == 6 and len({r["trial_id"] for r in rows}) == 6
    completed = [r for r in rows if r["completed"]]
    responses = []
    for row in completed:
        responses += [row["peer"]["response"], row["hop2_unguarded"]["response"]]
        responses += [c["response"] for c in row["hop1"]["calls"]]
        responses += [c["response"] for c in row["hop2_guarded"]["calls"]]
    metrics = {
        "phase": "two-hop integration smoke",
        "cases": len(rows),
        "errors": len(rows) - len(completed),
        "returned_provider_responses": len(responses),
        "first_receiver_correct": sum(
            r["hop1"]["baseline_oracle"]["task_complete"] for r in completed
        ),
        "unguarded_second_receiver_correct": sum(
            r["hop2_unguarded"]["oracle"]["task_complete"] for r in completed
        ),
        "guarded_second_receiver_correct": sum(
            bool(
                r["hop2_guarded"]["oracle"]
                and r["hop2_guarded"]["oracle"]["task_complete"]
            )
            for r in completed
        ),
        "poisoned_peer_proposals": sum(
            r["kind"] == "attack"
            and r["peer"]["oracle"]["extracted_facts"].get("budget")
            == r["target_budget"]
            for r in completed
        ),
    }
    (FOLDER / "metrics.json").write_text(json.dumps(metrics, indent=2) + "\n")
    (FOLDER / "COLLECTION_COMPLETE.json").write_text(
        json.dumps(metrics, indent=2) + "\n"
    )
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / "HANDOFF_SMOKE_METRICS.json").write_text(
        json.dumps(metrics, indent=2) + "\n"
    )
    report = f"""# Agent-handoff integration smoke

Six locally orchestrated peer → worker A → worker B cases completed with {metrics["errors"]} errors and {len(responses)} real Adaption responses. The peer used DeepSeek; both logical workers used stateless Gemma requests. Three deliberately poisoned proposals were generated by the peer as requested by the test driver; these are not spontaneous victim failures.

The first receiver was correct in {metrics["first_receiver_correct"]}/6 cases. The unguarded second receiver was correct in {metrics["unguarded_second_receiver_correct"]}/6; the guarded second receiver was correct in {metrics["guarded_second_receiver_correct"]}/6. Receivers already had authoritative source facts. Thus this smoke test shows the envelope/routing/guard integration works on these cases, **not incremental security benefit**. Separate downstream branches are different model draws.

This early smoke assigned one task to each language, so language and task are confounded. The subsequent matched multilingual pilot fixes that design by crossing the same tasks with all three languages; its results are reported separately. No subliminal bias, token search or TruthfulQA procedure from Thought Virus is reproduced.

Recompute with `uv run python scripts/report_agent_handoff.py`. Frozen inputs, code hashes, real model requests and responses, ingress audits and both outgoing branches are preserved in `runs/agent-handoff-smoke-v1`.
"""
    (ROOT / "research/AGENT_HANDOFF_SMOKE.md").write_text(report)
    (OUTPUT / "HANDOFF_SMOKE_REPORT.md").write_text(report)
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    main()
